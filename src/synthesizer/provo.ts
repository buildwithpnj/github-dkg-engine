import { GitHubPullRequest, GitHubIssue, TriModalKnowledgeAsset, MemoryLayer } from '../types/index.js';
import { SecretRedactor } from './redactor.js';

export class AssetSynthesizer {
  /**
   * Synthesizes a tri-modal Knowledge Asset from a GitHub Pull Request and review comments.
   */
  public static synthesizePullRequestAsset(
    repoOwner: string,
    repoName: string,
    pr: GitHubPullRequest,
    contextGraphId: string,
    memoryLayer: MemoryLayer = 'WM'
  ): TriModalKnowledgeAsset {
    const isAdr = pr.labels.some(l => 
      l.toLowerCase().includes('architecture') || 
      l.toLowerCase().includes('adr') || 
      l.toLowerCase().includes('decision')
    );

    const assetName = `github-pr-${repoOwner}-${repoName}-${pr.number}`;
    const entityUri = `urn:dkg:github:${repoOwner}:${repoName}:pr:${pr.number}`;
    const authorDid = `did:github:user:${pr.user.login}`;

    // 1. Narrative Markdown Generation
    const cleanBody = SecretRedactor.sanitizeMarkdown(pr.body || 'No description provided.');
    
    let reviewsSummary = '';
    if (pr.reviews && pr.reviews.length > 0) {
      reviewsSummary = `\n\n### Code Reviews & Discussion Highlights (${pr.reviews.length} comments)\n` +
        pr.reviews.slice(0, 10).map(r => {
          const cleanComment = SecretRedactor.sanitizeMarkdown(r.body);
          const location = r.path ? ` on \`${r.path}\`${r.line ? `:${r.line}` : ''}` : '';
          return `- **@${r.user.login}**${location} (${r.created_at}):\n  > ${cleanComment.replace(/\n/g, '\n  > ')}`;
        }).join('\n\n');
      if (pr.reviews.length > 10) {
        reviewsSummary += `\n\n_... ${pr.reviews.length - 10} additional review comments omitted for space._`;
      }
    }

    const narrativeMarkdown = `# GitHub Pull Request #${pr.number}: ${SecretRedactor.sanitizeMarkdown(pr.title)}

- **Repository:** \`${repoOwner}/${repoName}\`
- **Author:** @${pr.user.login}
- **State:** \`${pr.state.toUpperCase()}\`${pr.merged ? ' (MERGED)' : ''}
- **Base Branch:** \`${pr.base_branch}\`
- **Head Commit:** \`${pr.head_sha}\`
- **Source URL:** ${pr.html_url}
- **Decision Classification:** ${isAdr ? '🌟 Architecture Decision Record (ADR)' : 'Standard Pull Request'}
- **Labels:** ${pr.labels.length ? pr.labels.map(l => `\`${l}\``).join(', ') : 'None'}

## Description & Rationale
${cleanBody}
${reviewsSummary}

---
*Generated by @buildwithpnj/github-dkg-engine for OriginTrail DKG v10 Working Memory*
`;

    // 2. Structural W3C PROV-O Triples Generation (N-Quads / Turtle format)
    const isoDate = new Date(pr.updated_at || pr.created_at).toISOString();
    const cleanTitle = SecretRedactor.sanitizeMarkdown(pr.title).replace(/["\\]/g, '\\$&');

    const structuralTriples = `
<${entityUri}> <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> <http://schema.org/DigitalDocument> .
<${entityUri}> <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> <http://www.w3.org/ns/prov#Entity> .
<${entityUri}> <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> <https://ontology.origintrail.io/dkg/v10#KnowledgeAsset> .
<${entityUri}> <http://schema.org/name> "${cleanTitle}" .
<${entityUri}> <http://schema.org/url> <${pr.html_url}> .
<${entityUri}> <https://github.com/ontology#commitSha> "${pr.head_sha}" .
<${entityUri}> <https://github.com/ontology#state> "${pr.state}" .
<${entityUri}> <http://www.w3.org/ns/prov#wasAttributedTo> <${authorDid}> .
<${entityUri}> <http://www.w3.org/ns/prov#wasDerivedFrom> <${pr.html_url}> .
<${entityUri}> <http://www.w3.org/ns/prov#generatedAtTime> "${isoDate}"^^<http://www.w3.org/2001/XMLSchema#dateTime> .
<${entityUri}> <https://ontology.origintrail.io/dkg/v10#memoryLayer> "${memoryLayer}" .
<${entityUri}> <https://ontology.origintrail.io/dkg/v10#contextGraph> <urn:dkg:context:${contextGraphId}> .
`.trim();

    return {
      name: assetName,
      memoryLayer,
      contextGraphId,
      narrativeMarkdown,
      structuralTriples,
      metadata: {
        sourceUrl: pr.html_url,
        commitSha: pr.head_sha,
        author: pr.user.login,
        generatedAt: isoDate,
        tags: pr.labels,
        isArchitectureDecision: isAdr
      }
    };
  }

  /**
   * Synthesizes a tri-modal Knowledge Asset from a GitHub Issue and technical discussions.
   */
  public static synthesizeIssueAsset(
    repoOwner: string,
    repoName: string,
    issue: GitHubIssue,
    contextGraphId: string,
    memoryLayer: MemoryLayer = 'WM'
  ): TriModalKnowledgeAsset {
    const assetName = `github-issue-${repoOwner}-${repoName}-${issue.number}`;
    const entityUri = `urn:dkg:github:${repoOwner}:${repoName}:issue:${issue.number}`;
    const authorDid = `did:github:user:${issue.user.login}`;

    const cleanBody = SecretRedactor.sanitizeMarkdown(issue.body || 'No description provided.');
    const isoDate = new Date(issue.updated_at || issue.created_at).toISOString();
    const cleanTitle = SecretRedactor.sanitizeMarkdown(issue.title).replace(/["\\]/g, '\\$&');

    let commentsSummary = '';
    if (issue.comments && issue.comments.length > 0) {
      commentsSummary = `\n\n### Issue Discussion & Solution Findings (${issue.comments.length} comments)\n` +
        issue.comments.slice(0, 10).map(c => {
          const cleanComment = SecretRedactor.sanitizeMarkdown(c.body);
          return `- **@${c.user.login}** (${c.created_at}):\n  > ${cleanComment.replace(/\n/g, '\n  > ')}`;
        }).join('\n\n');
    }

    const narrativeMarkdown = `# GitHub Issue #${issue.number}: ${SecretRedactor.sanitizeMarkdown(issue.title)}

- **Repository:** \`${repoOwner}/${repoName}\`
- **Author:** @${issue.user.login}
- **Status:** \`${issue.state.toUpperCase()}\`
- **Source URL:** ${issue.html_url}
- **Labels:** ${issue.labels.length ? issue.labels.map(l => `\`${l}\``).join(', ') : 'None'}

## Problem Description
${cleanBody}
${commentsSummary}

---
*Stored in OriginTrail DKG v10 Working Memory via @buildwithpnj/github-dkg-engine*
`;

    const structuralTriples = `
<${entityUri}> <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> <http://schema.org/DigitalDocument> .
<${entityUri}> <http://www.w3.org/1999/02/22-rdf-syntax-ns#type> <http://www.w3.org/ns/prov#Entity> .
<${entityUri}> <http://schema.org/name> "${cleanTitle}" .
<${entityUri}> <http://schema.org/url> <${issue.html_url}> .
<${entityUri}> <http://www.w3.org/ns/prov#wasAttributedTo> <${authorDid}> .
<${entityUri}> <http://www.w3.org/ns/prov#wasDerivedFrom> <${issue.html_url}> .
<${entityUri}> <http://www.w3.org/ns/prov#generatedAtTime> "${isoDate}"^^<http://www.w3.org/2001/XMLSchema#dateTime> .
<${entityUri}> <https://ontology.origintrail.io/dkg/v10#memoryLayer> "${memoryLayer}" .
<${entityUri}> <https://ontology.origintrail.io/dkg/v10#contextGraph> <urn:dkg:context:${contextGraphId}> .
`.trim();

    return {
      name: assetName,
      memoryLayer,
      contextGraphId,
      narrativeMarkdown,
      structuralTriples,
      metadata: {
        sourceUrl: issue.html_url,
        author: issue.user.login,
        generatedAt: isoDate,
        tags: issue.labels,
        isArchitectureDecision: false
      }
    };
  }
}
